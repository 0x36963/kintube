-- Accounts, passwordless email login, and sessions.

create table users (
    id           uuid primary key,             -- UUIDv7, generated by the app
    email        text not null unique,         -- normalized (trimmed, lowercased) by the app
    display_name text not null,
    role         text not null default 'user' check (role in ('user', 'admin')),
    created_at   timestamptz not null default now(),
    deleted_at   timestamptz
);

-- One row per "email me a sign-in link" request. Each carries both a magic-link
-- token and a 6-digit code; using either one consumes the row.
create table login_tokens (
    id          uuid primary key,
    email       text not null,
    token_hash  bytea not null unique,         -- sha256(token); raw token only ever lives in the email
    code_hash   bytea not null,                -- sha256(id || code)
    attempts    int not null default 0,
    created_at  timestamptz not null default now(),
    expires_at  timestamptz not null,
    used_at     timestamptz,
    ip          text
);
create index login_tokens_email_recent on login_tokens (email, created_at desc);

create table sessions (
    id           uuid primary key,
    token_hash   bytea not null unique,        -- sha256(cookie value)
    user_id      uuid not null references users (id) on delete cascade,
    created_at   timestamptz not null default now(),
    last_seen_at timestamptz not null default now(),
    expires_at   timestamptz not null,         -- sliding idle expiry
    user_agent   text,
    ip           text
);
create index sessions_user on sessions (user_id);
