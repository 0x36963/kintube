import { type APIRequestContext, type Page, expect } from "@playwright/test";
import path from "node:path";

const MAILPIT = process.env.MAILPIT_URL ?? "http://localhost:8025";
export const FIXTURES = path.join(import.meta.dirname, ".fixtures");

export function uniqueEmail(prefix = "e2e") {
  return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}@example.com`;
}

/** Signs in through the UI with the emailed code. */
export async function signIn(page: Page, request: APIRequestContext, email = uniqueEmail()) {
  await page.goto("/login");
  await page.getByLabel("Email").fill(email);
  await page.getByRole("button", { name: "Continue with email" }).click();
  await expect(page.getByRole("heading", { name: "Check your email" })).toBeVisible();
  const search = () => request.get(`${MAILPIT}/api/v1/search`, { params: { query: `to:"${email}"` } });
  await expect.poll(async () => (await (await search()).json()).messages_count, { timeout: 10_000 }).toBe(1);
  const { messages } = await (await search()).json();
  await page.getByLabel("6-digit code").fill((messages[0].Subject as string).slice(0, 6));
  await expect(page.getByRole("heading", { name: /^Welcome/ })).toBeVisible();
  return email;
}

/** A 5 s 720p clip with audio, generated by `global-setup.ts`. */
export const CLIP = path.join(FIXTURES, "Garden party.mp4");

/** Uploads via the top bar's file input and waits for the upload (not processing) to finish. */
export async function upload(page: Page, file: string) {
  await page.getByRole("banner").getByTestId("upload-input").setInputFiles(file);
  await expect(page.getByTestId("upload-row").filter({ hasText: path.basename(file) })).toHaveAttribute("data-status", "done", {
    timeout: 60_000,
  });
}
